import { findReaction, chemicals as chemData, type ReactionRule } from '@/data/chemicals';

export interface SimulationResult {
  reaction: ReactionRule | null;
  limitingReagent: string | null;
  finalPH: number;
  reactionCompleteness: number; // 0-100%
  temperatureChange: number;
  effects: {
    colorChange?: string;
    gasProduced?: string;
    precipitate?: string;
    exothermic: boolean;
  };
  observations: string[];
}

export function simulateReaction(
  chem1Id: string,
  chem1Volume: number, // ml
  chem2Id: string,
  chem2Volume: number, // ml
): SimulationResult {
  const reaction = findReaction(chem1Id, chem2Id);
  const c1 = chemData.find(c => c.id === chem1Id);
  const c2 = chemData.find(c => c.id === chem2Id);

  if (!reaction || !c1 || !c2) {
    return {
      reaction: null,
      limitingReagent: null,
      finalPH: calculateMixedPH(c1?.pH ?? 7, chem1Volume, c2?.pH ?? 7, chem2Volume),
      reactionCompleteness: 0,
      temperatureChange: 0,
      effects: { exothermic: false },
      observations: ['No reaction observed between these chemicals.'],
    };
  }

  // Moles = Molarity × Volume(L)
  const moles1 = c1.molarity * (chem1Volume / 1000);
  const moles2 = c2.molarity * (chem2Volume / 1000);

  // Determine limiting reagent (simplified 1:1 stoichiometry)
  const limitingReagent = moles1 <= moles2 ? c1.name : c2.name;
  const limitingMoles = Math.min(moles1, moles2);
  const excessMoles = Math.max(moles1, moles2) - limitingMoles;
  const reactionCompleteness = Math.min(100, (limitingMoles / Math.max(moles1, moles2)) * 100);

  // Calculate final pH
  let finalPH = reaction.pHResult ?? 7;
  if (excessMoles > 0) {
    const excessChem = moles1 > moles2 ? c1 : c2;
    if (excessChem.type === 'acid') finalPH = Math.max(0, 7 - (excessMoles * 50));
    if (excessChem.type === 'base') finalPH = Math.min(14, 7 + (excessMoles * 50));
  }

  const tempChange = reaction.effects.temperatureChange * (reactionCompleteness / 100);

  const observations: string[] = [];
  observations.push(`Reaction: ${reaction.balancedEquation}`);
  observations.push(`Limiting reagent: ${limitingReagent}`);
  observations.push(`Reaction completeness: ${reactionCompleteness.toFixed(1)}%`);
  observations.push(`Temperature change: ${tempChange > 0 ? '+' : ''}${tempChange.toFixed(1)}°C`);
  observations.push(`Final pH: ${finalPH.toFixed(1)}`);

  if (reaction.effects.colorChange) observations.push(`Color change observed: ${reaction.effects.colorChange}`);
  if (reaction.effects.gasProduced) observations.push(`Gas produced: ${reaction.effects.gasProduced}`);
  if (reaction.effects.precipitate) observations.push(`Precipitate: ${reaction.effects.precipitate}`);

  return {
    reaction,
    limitingReagent,
    finalPH,
    reactionCompleteness,
    temperatureChange: tempChange,
    effects: { ...reaction.effects, exothermic: reaction.effects.exothermic },
    observations,
  };
}

function calculateMixedPH(pH1: number, vol1: number, pH2: number, vol2: number): number {
  const h1 = Math.pow(10, -pH1) * vol1;
  const h2 = Math.pow(10, -pH2) * vol2;
  const totalH = (h1 + h2) / (vol1 + vol2);
  return Math.max(0, Math.min(14, -Math.log10(totalH)));
}

export function generateLabReport(
  experimentTitle: string,
  objective: string,
  chemicals: string[],
  tools: string[],
  steps: string[],
  result: SimulationResult,
): string {
  const date = new Date().toLocaleDateString();
  let report = `
═══════════════════════════════════════
         LAB REPORT
═══════════════════════════════════════

Date: ${date}
Experiment: ${experimentTitle}

OBJECTIVE:
${objective}

MATERIALS:
Chemicals: ${chemicals.join(', ')}
Tools: ${tools.join(', ')}

PROCEDURE:
${steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}

OBSERVATIONS:
${result.observations.join('\n')}

DATA:
- Final pH: ${result.finalPH.toFixed(2)}
- Temperature Change: ${result.temperatureChange > 0 ? '+' : ''}${result.temperatureChange.toFixed(1)}°C
- Reaction Completeness: ${result.reactionCompleteness.toFixed(1)}%
${result.limitingReagent ? `- Limiting Reagent: ${result.limitingReagent}` : ''}

CONCLUSION:
The experiment "${experimentTitle}" was completed successfully.
${result.reaction ? `The reaction ${result.reaction.balancedEquation} was observed with ${result.reactionCompleteness.toFixed(0)}% completion.` : 'No chemical reaction was observed.'}
${result.effects.exothermic ? 'The reaction was exothermic, releasing heat to the surroundings.' : ''}
${result.effects.precipitate ? `A precipitate was formed: ${result.effects.precipitate}` : ''}

═══════════════════════════════════════
  Generated by Virtual Chemistry Lab
═══════════════════════════════════════
`;
  return report;
}
